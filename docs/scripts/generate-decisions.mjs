import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = fileURLToPath(new URL('../src/content/docs/decisions/', import.meta.url));

function field(text, name) {
  const value = new RegExp(`^${name}:\\s*(.+)$`, 'm').exec(text)?.[1]?.trim();
  if (!value) throw new Error(`ADR has no ${name}`);
  return value.startsWith('"') ? JSON.parse(value) : value.replace(/^'|'$/g, '');
}

export function readDecisions(path) {
  return readdirSync(path).filter((name) => /^ADR-\d+\.md$/.test(name)).sort().map((name) => {
    const text = readFileSync(join(path, name), 'utf8');
    const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1];
    if (!frontmatter) throw new Error(`${name} has no frontmatter`);
    return { slug: name.slice(0, -3), title: field(frontmatter, 'title'), status: field(frontmatter, 'adr_status') };
  });
}

export function renderDecisions(records) {
  const groups = [
    ['Current', records.filter((record) => !['Superseded', 'Deprecated'].includes(record.status))],
    ['Superseded and deprecated', records.filter((record) => ['Superseded', 'Deprecated'].includes(record.status))],
  ];
  const body = groups.map(([label, entries]) => {
    const rows = entries.map(({ slug, title, status }) => {
      const decision = title.replace(new RegExp(`^${slug}:\\s*`), '').replaceAll('|', '\\|');
      return `| [${slug}](${slug.toLowerCase()}/) | ${decision} | ${status} |`;
    });
    return `## ${label}\n\n${rows.length ? '| ADR | Decision | Status |\n|---|---|---|\n' + rows.join('\n') : 'No records.'}\n`;
  }).join('\n');
  return `---
title: Decisions
id: DOC-DECISIONS-INDEX-001
type: Reference
status: Active
updated: "2026-10-04"
summary: "The decision log, grouped by the status recorded in each ADR."
---

<!-- Generated by scripts/generate-decisions.mjs from ADR frontmatter. -->

Each architectural decision carries its context and rationale in its own record. This map is generated from the records' titles and statuses during the build.

${body}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(join(directory, 'index.md'), renderDecisions(readDecisions(directory)));
}
