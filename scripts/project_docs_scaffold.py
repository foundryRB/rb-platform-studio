"""Project pinned canonical documentation inputs into the runtime scaffold."""

from __future__ import annotations

import argparse
import os
import re
import subprocess
from pathlib import Path
from urllib.request import Request, urlopen

__all__ = ["main"]

REVISION = "0097a8f4c5c9b8524487a859ab9dc20c004d0b74"
SOURCE = "https://api.github.com/repos/foundryRB/rb-playbook/contents"
OVERVIEW = "galaxies/craft/skills/apply-intent-bundle/bundles/starlight/templates/overview.md"
BOOTSTRAP = "galaxies/craft/skills/bootstrap-starlight/bootstrap.py"
TARGET = Path(__file__).resolve().parents[1] / "studio-backend/studio/domain/services/docs_scaffold_source.py"


def read_source(path: str, source_root: Path | None) -> str:
    if source_root is not None:
        result = subprocess.run(
            ["git", "-C", str(source_root), "show", f"{REVISION}:{path}"],
            check=True, capture_output=True, encoding="utf-8",
        )
        return result.stdout.replace("\r\n", "\n")
    headers = {"Accept": "application/vnd.github.raw+json"}
    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = Request(f"{SOURCE}/{path}?ref={REVISION}", headers=headers)
    with urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8").replace("\r\n", "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, help="Optional checkout at the pinned revision")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    template = read_source(OVERVIEW, args.source_root)
    bootstrap = read_source(BOOTSTRAP, args.source_root)
    sidebar = re.search(r"      sidebar: \[\n(.*?)      \],", bootstrap, re.DOTALL)
    if sidebar is None:
        raise RuntimeError("Canonical bootstrap declares no documentation sidebar")
    groups = sidebar.group(1).replace("{{", "{").replace("}}", "}")
    text = (
        f'"""Pinned playbook documentation inputs ({REVISION})."""\n\n'
        '# Generated by scripts/project_docs_scaffold.py; do not edit.\n'
        '# ruff: noqa: E501\n'
        "from __future__ import annotations\n\n"
        '__all__ = ["OVERVIEW_TEMPLATE", "DOCS_SIDEBAR"]\n\n'
        "OVERVIEW_TEMPLATE = (\n"
        + "".join(f"    {line!r}\n" for line in template.splitlines(keepends=True))
        + ")\n\nDOCS_SIDEBAR = (\n"
        + "".join(f"    {line!r}\n" for line in groups.splitlines(keepends=True))
        + ")\n"
    )
    if args.check:
        if TARGET.read_text(encoding="utf-8") != text:
            raise RuntimeError("Documentation scaffold projection differs from pinned source")
    else:
        TARGET.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
